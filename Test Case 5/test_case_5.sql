select sale_id,avg(total_amount) over(partition by sale_date ROWS BETWEEN UNBOUNDED preceding AND CURRENT ROW) as daily_avg_sale FROM daily_sales;


with daily as(
select date_format(sale_date,'%y-%m') as months,sum(total_amount) as tot_amount from daily_sales group by date_format(sale_date,'%y-%m')
),
prev_tot as 
(select tot_amount,months,lag(tot_amount)over(order by months) as prev_sales from daily)
select months, ((tot_amount-prev_sales)/prev_sales)*100 as trend from prev_tot;



